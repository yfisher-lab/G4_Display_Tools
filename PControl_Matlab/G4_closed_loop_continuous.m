% Re-issuing startDisplay mid-trial would reintroduce the stale flash, so for
% very long trials prefer a longer single run or split the experiment into
% blocks with the animal briefly in true darkness between them (the FicTrac
% gate holding V_BLANK), which avoids a visible stale bar at each restart.
% -------------------------------------------------------------------------
